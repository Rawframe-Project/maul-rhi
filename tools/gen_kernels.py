# Compiles the library's own D3D12 kernels to DXIL with DXC, each with
# its root signature embedded, and writes each as bytes to
# src/generated/NAME.h. DXC signs the DXIL when its validator (libdxil)
# sits beside it. CI runs no DXC; the headers are committed, and this
# script is run again whenever a kernel's source changes.
#
# Each header carries a stamp (tools/shader_stamp.py): the digest of its
# inputs, the pinned DXC that made it (shader_stamp.DXC), and the digest
# of its bytes. The script refuses another DXC; --check tells, with no
# tools, whether every header still matches; --self-test proves that
# check on a copy of the tree (--skip-inputs turns off the input
# comparison, which the self-test must then fail).
#
# usage: gen_kernels.py [--check | --self-test [--skip-inputs] | path to dxc]

import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import shader_stamp  # noqa: E402

SCRIPTS = ["tools/gen_kernels.py", "tools/shader_stamp.py"]
# Each kernel: its source in src/, its header's name, and the array the
# header declares.
KERNELS = [("d3d12_expand.hlsl", "d3d12_expand.h", "mrhiD3d12ExpandDxil")]


def units(root):
    """Each header and the inputs it is made from, relative to the root."""
    return [(f"src/generated/{name}", [f"src/{source}"] + SCRIPTS)
            for source, name, _ in KERNELS]


def header(source, array, code, stamp):
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Copyright (c) 2026 Sirac Ozmen",
        "//",
        f"// Generated by tools/gen_kernels.py from src/{source}: its DXIL, with",
        "// the root signature embedded.",
        "//",
        *stamp,
        "",
        "// clang-format off",
        "",
        "#include <stdint.h>",
        "",
        f"static const uint8_t {array}[{len(code)}] = {{",
    ]
    for start in range(0, len(code), 12):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in code[start:start + 12]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    flags = [arg for arg in sys.argv[1:] if arg.startswith("--")]
    compare_inputs = "--skip-inputs" not in flags
    if "--self-test" in flags:
        copied = ["tools"] + [path for header, inputs in units(ROOT) for path in [header] + inputs
                              if not path.startswith("tools/")]
        return shader_stamp.self_test(ROOT, copied, units, shader_stamp.DXC, compare_inputs)
    if "--check" in flags:
        return shader_stamp.check(ROOT, units(ROOT), shader_stamp.DXC, "tools/gen_kernels.py",
                                  compare_inputs)
    if flags:
        sys.exit("usage: gen_kernels.py [--check | --self-test [--skip-inputs] | path to dxc]")
    dxc = sys.argv[1] if len(sys.argv) > 1 else "dxc"
    shader_stamp.refuse_unpinned({"dxc": shader_stamp.dxc_identity(dxc)},
                                 {"dxc": shader_stamp.DXC_IDENTITY})
    stamped = dict(units(ROOT))
    with tempfile.TemporaryDirectory() as work:
        for source, name, array in KERNELS:
            out = os.path.join(work, name + ".dxil")
            subprocess.run([dxc, "-T", "cs_6_0", "-E", "main", *shader_stamp.DXC_FLAGS, "-Fo",
                            out, os.path.join(ROOT, "src", source)], check=True)
            with open(out, "rb") as f:
                code = f.read()
            # DXC leaves the hash zero when it cannot sign.
            if code[4:20] == bytes(16):
                sys.exit(f"{source}: DXC did not sign the DXIL; is libdxil beside it?")
            stamp = shader_stamp.stamp_lines(ROOT, stamped[f"src/generated/{name}"],
                                             shader_stamp.DXC, code)
            with open(os.path.join(ROOT, "src", "generated", name), "w", encoding="utf-8",
                      newline="\n") as f:
                f.write(header(source, array, code, stamp))
            print(f"wrote src/generated/{name} ({len(code)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
