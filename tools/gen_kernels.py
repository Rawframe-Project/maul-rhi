# Compiles the library's own kernels and writes each as bytes to
# src/generated/NAME.h: the D3D12 ones (.hlsl) to DXIL with DXC, each with
# its root signature embedded, and the Vulkan ones (.comp) to SPIR-V with
# glslangValidator, checked by spirv-val for Vulkan 1.3. DXC signs the
# DXIL when its validator (libdxil) sits beside it. CI runs none of these
# tools; the headers are committed, and this script is run again
# whenever a kernel's source changes.
#
# Each header carries a stamp (tools/shader_stamp.py): the digest of its
# inputs, the pinned tools that made the kernels (PINS), and the digest
# of its bytes. The script refuses other tools; --check tells, with no
# tools, whether every header still matches; --self-test proves that
# check on a copy of the tree (--skip-inputs turns off the input
# comparison, which the self-test must then fail; it is refused without
# --self-test).
#
# usage: gen_kernels.py [--check | --self-test [--skip-inputs] | path to dxc]

import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import shader_stamp  # noqa: E402

SCRIPTS = ["tools/gen_kernels.py", "tools/shader_stamp.py"]
# Each kernel: its source in src/, its header's name, and the array the
# header declares.
KERNELS = [("d3d12_expand.hlsl", "d3d12_expand.h", "mrhiD3d12ExpandDxil"),
           ("d3d12_guard.hlsl", "d3d12_guard.h", "mrhiD3d12GuardDxil"),
           ("vulkan_guard.comp", "vulkan_guard.h", "mrhiVulkanGuardSpirv")]
# The glslang and SPIRV-Tools the SPIR-V kernels are made by, the test
# containers' (tools/gen_test_shaders.py), and every pin a header names.
GLSLANG = "glslang 15.1.0"
SPIRV_TOOLS = "SPIRV-Tools v2025.1"
PINS = (*shader_stamp.DXC, GLSLANG, SPIRV_TOOLS)
USAGE = "usage: gen_kernels.py [--check | --self-test [--skip-inputs] | path to dxc]"


def units(root):
    """Each header and the inputs it is made from, relative to the root."""
    return [(f"src/generated/{name}", [f"src/{source}"] + SCRIPTS)
            for source, name, _ in KERNELS]


def header(source, array, code, stamp):
    spirv = source.endswith(".comp")
    what = ["its SPIR-V, whose bytes", "a shader module takes as 32-bit words"] if spirv else [
        "its DXIL, with", "the root signature embedded"]
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Copyright (c) 2026 Sirac Ozmen",
        "//",
        f"// Generated by tools/gen_kernels.py from src/{source}: {what[0]}",
        *([f"// {what[1]}."] if len(what) > 1 else []),
        "//",
        *stamp,
        "",
        "// clang-format off",
        "",
        "#include <stdint.h>",
        "",
        f"static const uint8_t {array}[{len(code)}] = {{",
    ]
    for start in range(0, len(code), 12):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in code[start:start + 12]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def parse(argv):
    """The flags among argv. --skip-inputs is refused without --self-test,
    where it would quietly turn off the input comparison of --check."""
    flags = [arg for arg in argv if arg.startswith("--")]
    if "--skip-inputs" in flags and "--self-test" not in flags:
        sys.exit(USAGE)
    return flags


def main():
    flags = parse(sys.argv[1:])
    compare_inputs = "--skip-inputs" not in flags
    if "--self-test" in flags:
        copied = ["tools"] + [path for header, inputs in units(ROOT) for path in [header] + inputs
                              if not path.startswith("tools/")]
        return shader_stamp.self_test(ROOT, copied, units, PINS, parse, compare_inputs)
    if "--check" in flags:
        return shader_stamp.check(ROOT, units(ROOT), PINS, "tools/gen_kernels.py", compare_inputs)
    if flags:
        sys.exit(USAGE)
    dxc = sys.argv[1] if len(sys.argv) > 1 else "dxc"
    glslang = shader_stamp.output("glslangValidator", "--version").split("\n")[0]
    tools = " ".join(shader_stamp.output("spirv-link", "--version").split()[:2])
    shader_stamp.refuse_unpinned(
        {"dxc": shader_stamp.dxc_identity(dxc),
         "glslang": "glslang " + glslang.rsplit(":", 1)[-1].strip(), "SPIRV-Tools": tools},
        {"dxc": shader_stamp.DXC_IDENTITY, "glslang": GLSLANG, "SPIRV-Tools": SPIRV_TOOLS})
    stamped = dict(units(ROOT))
    with tempfile.TemporaryDirectory() as work:
        for source, name, array in KERNELS:
            out = os.path.join(work, name + ".bin")
            path = os.path.join(ROOT, "src", source)
            if source.endswith(".comp"):
                subprocess.run(["glslangValidator", "--quiet", "-V", "--target-env", "vulkan1.3",
                                "-o", out, path], check=True)
                subprocess.run(["spirv-val", "--target-env", "vulkan1.3", out], check=True)
            else:
                subprocess.run([dxc, "-T", "cs_6_0", "-E", "main", *shader_stamp.DXC_FLAGS,
                                "-Fo", out, path], check=True)
            with open(out, "rb") as f:
                code = f.read()
            # DXC leaves the hash zero when it cannot sign.
            if source.endswith(".hlsl") and code[4:20] == bytes(16):
                sys.exit(f"{source}: DXC did not sign the DXIL; is libdxil beside it?")
            stamp = shader_stamp.stamp_lines(ROOT, stamped[f"src/generated/{name}"], PINS, code)
            with open(os.path.join(ROOT, "src", "generated", name), "w", encoding="utf-8",
                      newline="\n") as f:
                f.write(header(source, array, code, stamp))
            print(f"wrote src/generated/{name} ({len(code)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
